// One-off: turns the live <text> wordmark in the lockup into a <path>, so the logo looks the same without
// the font installed (README, GitHub). Uses the Inter variable font NestBox already bundles.
// Run: node scripts/outline-wordmark.mjs   (writes resources/brand/svg/nestbox-lockup-outlined.svg)
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';
import wawoff from 'wawoff2';

const require = createRequire(import.meta.url);
const SOURCE = 'resources/brand/svg/nestbox-lockup.svg';
const TARGET = 'resources/brand/svg/nestbox-lockup-outlined.svg';
const FONT = require.resolve('@fontsource-variable/inter/files/inter-latin-wght-normal.woff2');

const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];

const woff2 = await readFile(FONT);
const ttf = await wawoff.decompress(woff2);
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));

const svg = await readFile(SOURCE, 'utf8');
const match = /<text\b([^>]*)>([^<]*)<\/text>/.exec(svg);
if (!match) throw new Error(`No <text> in ${SOURCE}`);
const [element, attrs = '', text = ''] = match;

const size = Number(attr(attrs, 'font-size') ?? 16);
const variation = { wght: Number(attr(attrs, 'font-weight') ?? 400) };
const spacing = Number(attr(attrs, 'letter-spacing') ?? 0);
const scale = size / font.unitsPerEm;
let x = Number(attr(attrs, 'x') ?? 0);
const y = Number(attr(attrs, 'y') ?? 0);

// Glyph by glyph: opentype.js's shaper can't run Inter's contextual lookups, and the wordmark needs none.
const glyphs = [...text].map((ch) => font.charToGlyph(ch));
const path = new opentype.Path();
glyphs.forEach((glyph, i) => {
  path.extend(glyph.getPath(x, y, size, { variation, hinting: false }, font));
  const advance = font.variation.getTransform(glyph, variation).advanceWidth;
  const next = glyphs[i + 1];
  x += advance * scale + spacing + (next ? font.getKerningValue(glyph, next) * scale : 0);
});

const outlined = `<path id="${attr(attrs, 'id') ?? 'wordmark'}" fill="${attr(attrs, 'fill') ?? 'currentColor'}" d="${path.toPathData(2)}"/>`;
const out = svg
  .replace(element, outlined)
  .replace(/<!-- Live text\.[^>]*-->\n?/, '<!-- Generated by scripts/outline-wordmark.mjs from nestbox-lockup.svg (Inter, outlined). -->\n');
await writeFile(TARGET, out);
const box = path.getBoundingBox();
console.log(`wrote ${TARGET}: wordmark spans x ${box.x1.toFixed(1)}–${box.x2.toFixed(1)}, y ${box.y1.toFixed(1)}–${box.y2.toFixed(1)}`);
